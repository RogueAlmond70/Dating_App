-- schema

CREATE TABLE users (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TYPE decision_status AS ENUM ('like', 'dislike', 'block', 'skip', 'pending');

CREATE TABLE likes (
    id SERIAL PRIMARY KEY,
    liker_id TEXT NOT NULL,      -- changed to TEXT to match users.id type
    liked_id TEXT NOT NULL,      -- changed to TEXT to match users.id type
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    decision decision_status,
    decision_at TIMESTAMP
);

CREATE INDEX idx_likes_liked_id ON likes (liked_id);
CREATE INDEX idx_likes_liker_id ON likes (liker_id);
CREATE INDEX idx_likes_liked_created ON likes (liked_id, created_at DESC);

